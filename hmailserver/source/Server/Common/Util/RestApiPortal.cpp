// The self-service portal as it is served: the page, the script it loads, and
// the headers both carry. Three string literals and nothing else - the routes
// that serve them are RestApiServer's HandlePortalPage_ and
// HandlePortalScript_, which declare these three names.
//
// Literals rather than files, deliberately: the portal answers on a listener
// that may be the only thing an installation has, and a page that depends on a
// file beside the binary is a page that is missing where somebody most needs
// it. build/check-portal-script.py parses the script from this file, so the
// three definitions keep their shape: a name, "=", and the string that follows,
// one string literal per line until the semicolon. That script then RUNS what
// it parsed, under build/portal-script-test.js, against a small DOM and a
// stubbed API - so a change here is answered by what the page then does, not by
// whether a substring survived.

