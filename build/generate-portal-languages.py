"""Embed the webmail's catalogues in the server.

Reads hmailserver/source/Server/Common/Util/PortalLanguages/<code>.json (one
object per language, English to translation) and writes
hmailserver/source/Server/Common/Util/PortalLanguagesData.cpp: for each
language, its catalogue as compact ASCII JSON in pieces of at most four
thousand characters (a compiler's limit on one literal is sixteen thousand;
the pieces are elements of an array, never concatenated by the compiler), and
a table of codes to pieces the server joins on first use.

Usage: generate-portal-languages.py [--print]   (--print writes to stdout)
build/check-portal-languages.py refuses a unit that is not what this writes.
"""
import io
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CATALOGUES = os.path.join(ROOT, "hmailserver", "source", "Server", "Common", "Util", "PortalLanguages")
OUT = os.path.join(ROOT, "hmailserver", "source", "Server", "Common", "Util", "PortalLanguagesData.cpp")
PIECE = 4000


def cpp_literal(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def identifier(code):
    return code.replace("-", "_")


def generate():
    files = sorted(f for f in os.listdir(CATALOGUES) if f.endswith(".json"))
    out = []
    out.append("// Copyright (c) 2026 Christopher Holloway / Progressive Robot Ltd and the hMailServer contributors")
    out.append("// SPDX-License-Identifier: AGPL-3.0-or-later")
    out.append("//")
    out.append("// Generated by build/generate-portal-languages.py from PortalLanguages/*.json -")
    out.append("// do not edit; edit a catalogue and run the generator.")
    out.append("")
    out.append('#include "StdAfx.h"')
    out.append('#include "PortalLanguages.h"')
    out.append("")
    out.append("namespace HM")
    out.append("{")
    out.append("   namespace")
    out.append("   {")
    for f in files:
        code = f[:-5]
        data = json.load(io.open(os.path.join(CATALOGUES, f), "r", encoding="utf-8"))
        text = json.dumps(data, ensure_ascii=True, separators=(",", ":"), sort_keys=True)
        out.append("      const char *const Pieces_%s[] =" % identifier(code))
        out.append("      {")
        for i in range(0, len(text), PIECE):
            out.append("         " + cpp_literal(text[i:i + PIECE]) + ",")
        out.append("         nullptr")
        out.append("      };")
    out.append("   }")
    out.append("")
    out.append("   const PortalLanguage PortalLanguages[] =")
    out.append("   {")
    for f in files:
        code = f[:-5]
        out.append('      { "%s", Pieces_%s },' % (code, identifier(code)))
    out.append("      { nullptr, nullptr }")
    out.append("   };")
    out.append("}")
    out.append("")
    return "\n".join(out)


def main():
    text = generate()
    if "--print" in sys.argv:
        sys.stdout.write(text)
        return 0
    io.open(OUT, "w", encoding="utf-8", newline="\r\n").write(text)
    print("written", OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
