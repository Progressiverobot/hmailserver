"""Embed the webmail's S/MIME module in the server.

Reads hmailserver/source/Server/Common/Util/PortalSmime.js - the module the
page loads as /portal-smime.js, and the one build/check-portal-smime.js runs
in Node against OpenSSL - and writes
hmailserver/source/Server/Common/Util/PortalSmimeData.cpp: the script in
pieces of at most four thousand characters (a compiler's limit on one literal
is sixteen thousand; the pieces are elements of an array the server joins on
first use), so the file served is the file checked, byte for byte.

Usage: generate-portal-smime.py [--print | --check]
  --print  writes the unit to stdout
  --check  exits 1 when the committed unit is not what the module would make
"""
import io
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODULE = os.path.join(ROOT, "hmailserver", "source", "Server", "Common", "Util", "PortalSmime.js")
OUT = os.path.join(ROOT, "hmailserver", "source", "Server", "Common", "Util", "PortalSmimeData.cpp")
PIECE = 4000


def cpp_literal(s):
    out = []
    for ch in s:
        code = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            continue
        elif ch == "\t":
            out.append("\\t")
        elif code < 0x20 or code > 0x7e:
            # Non-ASCII goes as its UTF-8 bytes in hex escapes, each followed by
            # a break so a following hex digit is not swallowed by the escape.
            for b in ch.encode("utf-8"):
                out.append("\\x%02x\"\"" % b)
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def generate():
    text = io.open(MODULE, "r", encoding="utf-8").read().replace("\r\n", "\n")
    out = []
    out.append("// Copyright (c) 2026 Christopher Holloway / Progressive Robot Ltd and the hMailServer contributors")
    out.append("// SPDX-License-Identifier: AGPL-3.0-or-later")
    out.append("//")
    out.append("// Generated by build/generate-portal-smime.py from PortalSmime.js - do not")
    out.append("// edit; edit the module and run the generator.")
    out.append("")
    out.append('#include "StdAfx.h"')
    out.append("")
    out.append("namespace HM")
    out.append("{")
    # extern on the definition: a const at namespace scope has internal linkage
    # otherwise, and RestApiSmime.cpp reaches it from another unit.
    out.append("   extern const char *const PortalSmimeScriptPieces[] =")
    out.append("   {")
    for i in range(0, len(text), PIECE):
        out.append("      " + cpp_literal(text[i:i + PIECE]) + ",")
    out.append("      nullptr")
    out.append("   };")
    out.append("}")
    out.append("")
    return "\n".join(out)


def main():
    text = generate()
    if "--print" in sys.argv:
        sys.stdout.write(text)
        return 0
    if "--check" in sys.argv:
        current = io.open(OUT, "r", encoding="utf-8").read().replace("\r\n", "\n") if os.path.exists(OUT) else ""
        if current != text:
            print("PortalSmimeData.cpp is not what PortalSmime.js would generate; run build/generate-portal-smime.py")
            return 1
        print("PortalSmimeData.cpp is current")
        return 0
    io.open(OUT, "w", encoding="utf-8", newline="\n").write(text)
    print("wrote " + OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
