"""Embed the webmail's page in the server.

Reads, from hmailserver/source/Server/Common/Util/, the four files the portal
is served from - Portal.html (the page, its stylesheet inline), Portal.js (the
script it loads as /portal.js), Portal.webmanifest and PortalServiceWorker.js -
and writes PortalPageData.cpp beside them: each file in pieces of at most four
thousand characters (a compiler's limit on one literal is sixteen thousand; the
pieces are elements of an array the server joins on first use), so the file
served is the file checked, byte for byte. The same arrangement as the S/MIME
module and build/generate-portal-smime.py.

Usage: generate-portal-page.py [--print | --check]
  --print  writes the unit to stdout
  --check  exits 1 when the committed unit is not what the files would make
"""

import io
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
UTIL = os.path.join(ROOT, "hmailserver", "source", "Server", "Common", "Util")
OUT = os.path.join(UTIL, "PortalPageData.cpp")
PIECE = 4000

# The array each file becomes, and the file.
PARTS = [
    ("PortalHtmlPieces", "Portal.html"),
    ("PortalScriptPieces", "Portal.js"),
    ("PortalManifestPieces", "Portal.webmanifest"),
    ("PortalServiceWorkerPieces", "PortalServiceWorker.js"),
]


def cpp_literal(s):
    out = []
    for ch in s:
        code = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            continue
        elif ch == "\t":
            out.append("\\t")
        elif code < 0x20 or code > 0x7e:
            # Non-ASCII goes as its UTF-8 bytes in hex escapes, each followed by
            # a break so a following hex digit is not swallowed by the escape.
            for b in ch.encode("utf-8"):
                out.append("\\x%02x\"\"" % b)
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def generate():
    out = []
    out.append("// https://www.progressiverobot.com")
    out.append("// Copyright (c) 2026 Christopher Holloway / Progressive Robot Ltd")
    out.append("// SPDX-License-Identifier: AGPL-3.0-or-later")
    out.append("")
    out.append("// Generated by build/generate-portal-page.py from Portal.html, Portal.js,")
    out.append("// Portal.webmanifest and PortalServiceWorker.js - do not edit; edit those")
    out.append("// and run the generator.")
    out.append("")
    out.append('#include "StdAfx.h"')
    out.append("")
    out.append("namespace HM")
    out.append("{")
    for index, (name, file) in enumerate(PARTS):
        text = io.open(os.path.join(UTIL, file), "r", encoding="utf-8").read().replace("\r\n", "\n")
        if index:
            out.append("")
        # extern on the definition: a const at namespace scope has internal
        # linkage otherwise, and RestApiServer.cpp reaches it from another unit.
        out.append("   extern const char *const %s[] =" % name)
        out.append("   {")
        for i in range(0, len(text), PIECE):
            out.append("      " + cpp_literal(text[i:i + PIECE]) + ",")
        out.append("      nullptr")
        out.append("   };")
    out.append("}")
    out.append("")
    return "\n".join(out)


def main():
    text = generate()
    if "--print" in sys.argv:
        sys.stdout.write(text)
        return 0
    if "--check" in sys.argv:
        current = io.open(OUT, "r", encoding="utf-8").read().replace("\r\n", "\n") if os.path.exists(OUT) else ""
        if current != text:
            print("PortalPageData.cpp is not what the portal's files would generate; run build/generate-portal-page.py")
            return 1
        print("PortalPageData.cpp is current")
        return 0
    with io.open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote " + OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
